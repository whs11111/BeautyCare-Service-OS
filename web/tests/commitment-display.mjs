import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { commitmentDisplay } from '../src/utils/commitmentDisplay.js';
const now = Date.parse('2026-10-18T02:00:00+08:00');
const timedTask = minutes => ({ dueAt: new Date(now + minutes * 60000).toISOString(), reminderEligible: false });
assert.equal(commitmentDisplay(timedTask(10.01), now).visible, false);
assert.equal(commitmentDisplay(timedTask(10), now).text, '剩余 10分0秒');
assert.equal(commitmentDisplay(timedTask(5), now).visible, true, 'Short promises get card countdowns too');
assert.equal(commitmentDisplay(timedTask(0), now).text, '已超时');
assert.equal(commitmentDisplay(timedTask(-1), now).overdue, true);
assert.equal(commitmentDisplay({ dueAt: null }, now).visible, false);
assert.equal(commitmentDisplay({ dueAt: 'invalid' }, now).overdue, false);
const customer = await readFile(new URL('../src/views/CustomerChat.vue', import.meta.url), 'utf8');
const quick = customer.slice(customer.indexOf('<div class="quick">'), customer.indexOf('<div class="client-composer">'));
assert(quick.indexOf('class="quiz-entry"') < quick.indexOf('>物流问题</button>'), 'Quiz recommendation must be the first shortcut');
const list = await readFile(new URL('../src/components/CommitmentList.vue', import.meta.url), 'utf8');
assert(list.includes("filter(task => task.status === 'OPEN')"), 'Short and undated promises remain visible');
assert(list.includes('display(task).visible') && list.includes("'commitment-overdue': display(task).overdue"), 'Cards use the ten-minute countdown and overdue background');
assert(list.includes('@click="openTask(task)"') && list.includes(':disabled="!canManage(task)"'), 'Whole promise card opens the editor with ownership protection');
assert(!list.includes('延后 / 结束提醒'), 'No redundant text button inside promise card');
const reminders = await readFile(new URL('../src/components/DeadlineReminders.vue', import.meta.url), 'utf8');
assert(reminders.includes('task.reminderEligible !== false') && reminders.includes('<= 15 * 60 * 1000'));
console.log('PASS quiz shortcut first; ten-minute card countdown including short promises; overdue background; popup threshold unchanged');
