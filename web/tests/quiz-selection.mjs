import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { profileCustomerId, quizUrl, selectQuizOption } from '../src/utils/quizSelection.js';
const quiz = JSON.parse(await readFile(new URL('../../server-v2/server/src/main/resources/quiz/skin-quiz.json', import.meta.url), 'utf8'));
const intolerance = quiz.questions.find(q => q.id === 'intolerance');
assert.deepEqual(selectQuizOption(intolerance, ['alcohol'], 'none'), ['none']);
assert.deepEqual(selectQuizOption(intolerance, ['none'], 'fragrance'), ['fragrance']);
assert.deepEqual(selectQuizOption(intolerance, ['alcohol'], 'alcohol'), []);
const goals = quiz.questions.find(q => q.id === 'goals');
assert.deepEqual(selectQuizOption(goals, ['red', 'dry', 'oil'], 'acne'), ['red', 'dry', 'oil']);
const single = quiz.questions.find(q => q.id === 'budget');
assert.deepEqual(selectQuizOption(single, ['b200'], 'b400'), ['b400']);
assert.equal(profileCustomerId(5), 'conversation-5');
assert.equal(quizUrl(5), '/quiz.html?c=conversation-5');
const frontend = await readFile(new URL('../public/quiz.html', import.meta.url), 'utf8');
const backend = await readFile(new URL('../../server-v2/server/src/main/resources/static/quiz.html', import.meta.url), 'utf8');
assert.equal(frontend, backend, 'static frontend and backend survey copies stay identical');
assert(frontend.includes('beautycare-profile-update') && frontend.includes('consent'));
console.log('PASS exclusive/multi/single selections, canonical identity, matching static entry points and profile notification');
