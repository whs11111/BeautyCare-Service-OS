import assert from 'node:assert/strict';
import { updateProfileNotice } from '../src/utils/profileNotifications.js';
const chat = { id: 'f1', dimension: 'skinType', value: '干皮', source: 'CHAT', evidenceMessageIds: ['u1'], mentions: 1, status: 'STATED' };
const quiz = { id: 'f2', dimension: 'concern', value: '干燥起皮', source: 'QUIZ', evidenceMessageIds: ['quiz'], mentions: 1, status: 'CONFIRMED' };
let state = updateProfileNotice(null, []);
assert.equal(state.unread, false);
state = updateProfileNotice(state, [chat]);
assert.equal(state.unread, true, 'New chat profile raises badge');
state = updateProfileNotice(state, [chat], true);
assert.equal(state.unread, false, 'Viewing profile clears badge');
state = updateProfileNotice(state, [{ ...chat, status: 'CONFIRMED', updatedAt: 'later' }]);
assert.equal(state.unread, false, 'Confirmation or refresh timestamps are not new consumer information');
state = updateProfileNotice(state, [chat, quiz]);
assert.equal(state.unread, true, 'Quiz feedback raises badge');
state = updateProfileNotice(state, [quiz, chat], true);
state = updateProfileNotice(state, [chat, quiz]);
assert.equal(state.unread, false, 'Polling and ordering changes do not raise badge');
state = updateProfileNotice(state, [{ ...chat, evidenceMessageIds: ['u1', 'u2'], mentions: 2 }, quiz]);
assert.equal(state.unread, true, 'New supporting user statement raises badge');
assert.equal(updateProfileNotice(state, [chat, quiz], true).unread, false);
const otherCustomer = updateProfileNotice(null, []);
assert.equal(otherCustomer.unread, false, 'Customer states remain independent');
assert.equal(updateProfileNotice({ revisions: state.revisions, unread: false }, [quiz]).unread, false, 'Removing a fact does not create a notification');
console.log('PASS chat/quiz profile notifications, viewed acknowledgement, independent customers and no refresh-only badges');
