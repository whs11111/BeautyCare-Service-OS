import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { fileURLToPath } from 'node:url';

const server = await createServer({ root: fileURLToPath(new URL('..', import.meta.url)), server: { middlewareMode: true }, appType: 'custom' });
try {
  const { createPinia } = await server.ssrLoadModule('pinia');
  const { useChatStore } = await server.ssrLoadModule('/src/store/chat.js');
  const { assistanceWorkflowApi: api } = await server.ssrLoadModule('/src/api/http.js');
  assert(!('extractPending' in api), 'no standalone LoRA pending API');
  const store = useChatStore(createPinia());
  store.activeId = 1;
  store.viewMode = null;
  store.refreshReplyDraft = async () => {};
  store.persistConversations = () => {};
  const conversation = store.conversations[0];
  conversation.messages = [{ id: 'm1', from: 'user', text: '补发物流到哪里了', time: '10:00' }];
  const deferred = () => {
    let resolve;
    const promise = new Promise(yes => { resolve = yes; });
    return { promise, resolve: data => resolve({ data }) };
  };
  const tick = () => new Promise(resolve => setImmediate(resolve));
  const context = deferred(), risk = deferred();
  let contexts = 0;
  api.buildContext = () => { contexts++; return context.promise; };
  api.analyzeRisk = () => risk.promise;
  const run = store.refreshAssistance(1);
  risk.resolve({ emotion: 'negative', emotionScore: 65, riskScore: 20, evidence: [], handoffRequired: false });
  await tick();
  assert.equal(conversation.emotionScore, 65);
  assert(store.contextRefreshIds.includes(1), 'cloud context can still be loading after risk');
  context.resolve({ unresolvedEvents: [{ description: '核实补发物流', sourceMessageId: 'm1' }], workflowStatus: '等待查询物流', timeline: [] });
  await run;
  await tick();
  assert.equal(contexts, 1, 'one context request, no duplicate cloud analysis');
  assert.equal(conversation.unresolvedEvents[0].sourceMessageId, 'm1');
  assert.equal(conversation.workflowStatus, '等待查询物流');
  console.log('PASS risk updates independently; pending events come from one cloud context request');

  const older = deferred(), newer = deferred();
  api.buildContext = () => older.promise;
  const first = store.refreshSummaries(1);
  conversation.messages.push({ id: 'm2', from: 'user', text: '还没收到' });
  api.buildContext = () => newer.promise;
  const second = store.refreshSummaries(1);
  newer.resolve({ unresolvedEvents: [{ description: '核实未收到问题', sourceMessageId: 'm2' }], workflowStatus: '查询中' });
  await second;
  older.resolve({ unresolvedEvents: [], workflowStatus: '旧结果' });
  await first;
  assert.equal(conversation.unresolvedEvents[0].sourceMessageId, 'm2');
  api.buildContext = () => Promise.reject(new Error('DeepSeek unavailable'));
  await store.refreshSummaries(1);
  assert.equal(conversation.unresolvedEvents[0].sourceMessageId, 'm2');
  assert.equal(store.contextRefreshErrors[1], 'DeepSeek unavailable');
  api.buildContext = async () => ({ data: { unresolvedEvents: [], workflowStatus: '已答复' } });
  await store.refreshSummaries(1);
  assert.equal(conversation.unresolvedEvents.length, 0);
  assert(!store.contextRefreshErrors[1]);
  console.log('PASS cloud pending refresh ignores stale responses, preserves old result on error, and clears completed events');
  const { useReceptionStore } = await server.ssrLoadModule('/src/store/reception.js');
  const reception = useReceptionStore();
  reception.identity = { token: 'offline-test', agent: { id: 'agent1' } };
  reception.ready = true;
  reception.reportAnalysis = async () => {};
  conversation.reception = { mode: 'HUMAN', status: 'active', agentId: 'agent1', emotionAnalysisOwner: 'server', emotionAnalysisPending: true };
  conversation.messages.push({ id: 'm3', from: 'user', text: '又等了一天' });
  store.activeId = 5;
  store.viewMode = 'agent';
  let duplicateRiskCalls = 0, unselectedDraftCalls = 0;
  api.analyzeRisk = async () => { duplicateRiskCalls++; throw new Error('Duplicate server-owned analysis'); };
  store.refreshReplyDraft = async () => { unselectedDraftCalls++; };
  await store.refreshAssistance(1);
  await tick();
  assert.equal(duplicateRiskCalls, 0);
  assert.equal(unselectedDraftCalls, 0);
  assert.equal(conversation.needsAnalysis, true);
  console.log('PASS server-owned emotion analysis works independently; unselected chats do not generate duplicate risk/draft requests');
} finally { await server.close(); }
